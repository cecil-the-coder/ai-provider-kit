// TestMapGeminiFinishReasonToStandard tests the mapGeminiFinishReasonToStandard function
func TestMapGeminiFinishReasonToStandard(t *testing.T) {
	tests := []struct {
		name         string
		finishReason string
		hasToolCalls bool
		want         string
	}{
		// STOP mappings
		{
			name:         "STOP without tool calls",
			finishReason: string(FinishReasonStop),
			hasToolCalls: false,
			want:         "stop",
		},
		{
			name:         "STOP with tool calls",
			finishReason: string(FinishReasonStop),
			hasToolCalls: true,
			want:         "tool_calls",
		},
		// Length mapping
		{
			name:         "MAX_TOKENS maps to length",
			finishReason: string(FinishReasonMaxTokens),
			hasToolCalls: false,
			want:         "length",
		},
		// Content filter mappings
		{
			name:         "SAFETY maps to content_filter",
			finishReason: string(FinishReasonSafety),
			hasToolCalls: false,
			want:         "content_filter",
		},
		{
			name:         "RECITATION maps to content_filter",
			finishReason: string(FinishReasonRecitation),
			hasToolCalls: false,
			want:         "content_filter",
		},
		{
			name:         "LANGUAGE maps to content_filter",
			finishReason: string(FinishReasonLanguage),
			hasToolCalls: false,
			want:         "content_filter",
		},
		{
			name:         "BLOCKLIST maps to content_filter",
			finishReason: string(FinishReasonBlocklist),
			hasToolCalls: false,
			want:         "content_filter",
		},
		{
			name:         "PROHIBITED_CONTENT maps to content_filter",
			finishReason: string(FinishReasonProhibitedContent),
			hasToolCalls: false,
			want:         "content_filter",
		},
		{
			name:         "SPII maps to content_filter",
			finishReason: string(FinishReasonSpii),
			hasToolCalls: false,
			want:         "content_filter",
		},
		{
			name:         "IMAGE_SAFETY maps to content_filter",
			finishReason: string(FinishReasonImageSafety),
			hasToolCalls: false,
			want:         "content_filter",
		},
		{
			name:         "IMAGE_PROHIBITED_CONTENT maps to content_filter",
			finishReason: string(FinishReasonImageProhibitedContent),
			hasToolCalls: false,
			want:         "content_filter",
		},
		// Tool call error mappings
		{
			name:         "MALFORMED_FUNCTION_CALL maps to tool_calls",
			finishReason: string(FinishReasonMalformedFunctionCall),
			hasToolCalls: false,
			want:         "tool_calls",
		},
		{
			name:         "UNEXPECTED_TOOL_CALL maps to tool_calls",
			finishReason: string(FinishReasonUnexpectedToolCall),
			hasToolCalls: false,
			want:         "tool_calls",
		},
		{
			name:         "TOO_MANY_TOOL_CALLS maps to tool_calls",
			finishReason: string(FinishReasonTooManyToolCalls),
			hasToolCalls: false,
			want:         "tool_calls",
		},
		// Other mappings
		{
			name:         "NO_IMAGE maps to stop",
			finishReason: string(FinishReasonNoImage),
			hasToolCalls: false,
			want:         "stop",
		},
		{
			name:         "IMAGE_OTHER maps to stop",
			finishReason: string(FinishReasonImageOther),
			hasToolCalls: false,
			want:         "stop",
		},
		{
			name:         "OTHER maps to stop",
			finishReason: string(FinishReasonOther),
			hasToolCalls: false,
			want:         "stop",
		},
		{
			name:         "Unknown reason maps to stop",
			finishReason: "UNKNOWN",
			hasToolCalls: false,
			want:         "stop",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := mapGeminiFinishReasonToStandard(tt.finishReason, tt.hasToolCalls)
			if got != tt.want {
				t.Errorf("mapGeminiFinishReasonToStandard(%q, %v) = %q, want %q",
					tt.finishReason, tt.hasToolCalls, got, tt.want)
			}
		})
	}
}

