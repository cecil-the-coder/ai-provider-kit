// TestGetFinishReasonMessage tests the GetFinishReasonMessage function
func TestGetFinishReasonMessage(t *testing.T) {
	tests := []struct {
		name         string
		finishReason string
		want         string
	}{
		{
			name:         "STOP reason",
			finishReason: string(FinishReasonStop),
			want:         "response completed successfully",
		},
		{
			name:         "MAX_TOKENS reason",
			finishReason: string(FinishReasonMaxTokens),
			want:         "maximum token limit reached",
		},
		{
			name:         "SAFETY reason",
			finishReason: string(FinishReasonSafety),
			want:         "content was flagged for safety concerns",
		},
		{
			name:         "RECITATION reason",
			finishReason: string(FinishReasonRecitation),
			want:         "content was flagged for potential recitation of copyrighted material",
		},
		{
			name:         "LANGUAGE reason",
			finishReason: string(FinishReasonLanguage),
			want:         "content was flagged for using an unsupported language",
		},
		{
			name:         "BLOCKLIST reason",
			finishReason: string(FinishReasonBlocklist),
			want:         "content contains forbidden terms from blocklist",
		},
		{
			name:         "PROHIBITED_CONTENT reason",
			finishReason: string(FinishReasonProhibitedContent),
			want:         "content was blocked for potentially containing prohibited content",
		},
		{
			name:         "SPII reason",
			finishReason: string(string(FinishReasonSpii)),
			want:         "content was blocked for potentially containing Sensitive Personally Identifiable Information (SPII)",
		},
		{
			name:         "MALFORMED_FUNCTION_CALL reason",
			finishReason: string(FinishReasonMalformedFunctionCall),
			want:         "function call generated by the model is invalid (consider using function calling mode ANY for constrained decoding)",
		},
		{
			name:         "IMAGE_SAFETY reason",
			finishReason: string(FinishReasonImageSafety),
			want:         "generated images contain safety violations",
		},
		{
			name:         "UNEXPECTED_TOOL_CALL reason",
			finishReason: string(FinishReasonUnexpectedToolCall),
			want:         "model generated a tool call but no tools were enabled in the request",
		},
		{
			name:         "TOO_MANY_TOOL_CALLS reason",
			finishReason: string(FinishReasonTooManyToolCalls),
			want:         "model called too many tools consecutively",
		},
		{
			name:         "IMAGE_PROHIBITED_CONTENT reason",
			finishReason: string(FinishReasonImageProhibitedContent),
			want:         "generated images contain prohibited content",
		},
		{
			name:         "IMAGE_OTHER reason",
			finishReason: string(FinishReasonImageOther),
			want:         "image generation stopped due to miscellaneous issue",
		},
		{
			name:         "NO_IMAGE reason",
			finishReason: string(FinishReasonNoImage),
			want:         "model was expected to generate an image but none was generated",
		},
		{
			name:         "OTHER reason",
			finishReason: string(FinishReasonOther),
			want:         "generation stopped for unknown reason",
		},
		{
			name:         "UNSPECIFIED reason",
			finishReason: string(FinishReasonUnspecified),
			want:         "finish reason unspecified",
		},
		{
			name:         "Empty reason",
			finishReason: "",
			want:         "finish reason unspecified",
		},
		{
			name:         "Unknown reason",
			finishReason: "UNKNOWN_REASON",
			want:         "generation stopped with reason: UNKNOWN_REASON",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := GetFinishReasonMessage(tt.finishReason)
			if got != tt.want {
				t.Errorf("GetFinishReasonMessage(%q) = %q, want %q", tt.finishReason, got, tt.want)
			}
		})
	}
}

